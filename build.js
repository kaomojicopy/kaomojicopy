/* sitemap dates: a page's <lastmod> only changes when its generated HTML changes */
const crypto = require("crypto");
const today = new Date().toISOString().slice(0, 10);
let lm = {};
try { lm = JSON.parse(rd("data/lastmod.json")); } catch (e) {}
const emitted = new Set();
const emit = (rel, html) => {
  wr(rel, html); emitted.add(rel);
  /* the site address is ignored when deciding whether a page changed, so moving to a new domain does not reset every sitemap date */
  const md5 = s => crypto.createHash("md5").update(s).digest("hex");
  const hRaw = md5(html), hNorm = md5(base ? html.split(base).join("{{SITE}}") : html);
  if (!lm[rel] || (lm[rel].h !== hNorm && lm[rel].h !== hRaw)) lm[rel] = { h: hNorm, d: today }; else lm[rel].h = hNorm;
};

