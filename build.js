/* Build script. Edit the files in data/ (and templates/ for page text), then run:  node build.js
   It writes index.html, 404.html, kaomoji/<slug>.html, sitemap.xml, robots.txt and assets/js/data.js. */
const fs = require("fs"), path = require("path");
const rd = f => fs.readFileSync(path.join(__dirname, f), "utf8");
/* Output folder. By default the pages are written next to the sources (GitHub Pages style).
   Set OUT_DIR=dist to write a clean copy to dist/ instead (Netlify: only dist/ is published, so data/ and templates/ stay private). */
const OUT = process.env.OUT_DIR ? path.resolve(__dirname, process.env.OUT_DIR) : __dirname;
const wr = (f, t) => { const p = path.join(OUT, f); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, t); };
const wrSrc = (f, t) => fs.writeFileSync(path.join(__dirname, f), t); /* build state that must stay in the repo */
const site = JSON.parse(rd("data/site.json"));
const allCats = JSON.parse(rd("data/categories.json"));
const cats = allCats.filter(c => !c.dir);                     // kaomoji collections (home page, search, generator)
const emojiCats = allCats.filter(c => c.dir === "emoji");      // emoji collections (own pages under /emoji/)
const emojiItems = JSON.parse(rd("data/emoji.json"));          // [emoji, collection, official name, popularity]
const emojiHub = JSON.parse(rd("data/emoji-hub.json"));
const faces = JSON.parse(rd("data/faces.json")); // [face, category, note, popularity 0-100]
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const fill = (t, v) => t.replace(/\{\{(\w+)\}\}/g, (m, k) => (v[k] !== undefined ? v[k] : m));
/* long-form content: [text](/path.html) links are turned into relative links for the page they appear on */
const inline = (s, root) => esc(s).replace(/\[([^\]]+)\]\((\/[^)\s]*)\)/g, (m, t, u) => `<a href="${root}${u.slice(1)}">${t}</a>`);
const paras = (s, root) => String(s).split(/\n\n/).map(p => `<p>${inline(p, root)}</p>`).join("");
const table = t => `<div class="table-wrap"><table><thead><tr>${t.head.map(h => `<th scope="col">${esc(h)}</th>`).join("")}</tr></thead><tbody>${t.rows.map(r => `<tr>${r.map((c, i) => `<td${i === 0 ? ' class="sym"' : ""}>${esc(c)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
const block = (x, root) => `<h2>${esc(x.h)}</h2>` + (x.p ? paras(x.p, root) : "") + (x.list ? `<ul>${x.list.map(i => `<li>${inline(i, root)}</li>`).join("")}</ul>` : "") + (x.table ? table(x.table) : "");
const prose = (secs, root) => (secs || []).length ? `<section class="shell page-sec prose">` + secs.map(x => block(x, root)).join("") + `</section>` : "";

const labels = {}, kw = {};
